def count_pairs(S, Hn):
    """number of ordered pairs (i,j) with lambda_i . lambda_j = 0 (i.e. alpha_x.beta_x=0), chunked"""
    HS = S @ Hn
    tot = 0
    for a in range(0, len(S), CHUNK):
        tot += int(((S[a:a + CHUNK] @ HS.T) == 0).sum())
    return tot

def get_pairs(S, Hn):
    HS = S @ Hn
    out = []
    for a in range(0, len(S), CHUNK):
        D = S[a:a + CHUNK] @ HS.T
        p = np.argwhere(D == 0); p[:, 0] += a
        out.append(p)
    return np.concatenate(out) if out else np.zeros((0, 2), dtype=np.int64)

def vector_invariants(S, Hn):
    """Distinct values of a cheap O(Gamma)-invariant of the ordered pair (lambda_a,lambda_b), unimodular Gamma:
    (content(a), content(b), content(a+b), content(a-b), gcd of all 2x2 minors of [a;b]).  A LOWER-bound tool only (not complete)."""
    r = S.shape[1]
    idx = [(p, q) for p in range(r) for q in range(p + 1, r)]
    keys = set()
    HS = S @ Hn
    for a in range(0, len(S), CHUNK):
        D = S[a:a + CHUNK] @ HS.T
        pi, pj = np.nonzero(D == 0)
        if len(pi) == 0:
            continue
        A = S[a:a + CHUNK][pi]; B = S[pj]
        ca = np.gcd.reduce(np.abs(A), axis=1); cb = np.gcd.reduce(np.abs(B), axis=1)
        cp = np.gcd.reduce(np.abs(A + B), axis=1); cm = np.gcd.reduce(np.abs(A - B), axis=1)
        mg = np.zeros(len(A), dtype=np.int64)
        for p, q in idx:
            mg = np.gcd(mg, np.abs(A[:, p] * B[:, q] - A[:, q] * B[:, p]))
        K = np.stack([ca, cb, cp, cm, mg], axis=1)
        for k in np.unique(K, axis=0):
            keys.add(tuple(int(x) for x in k))
    return keys

def greedy_reduce(la, lb, gens_and_inv, max_iter=400):
    """apply group generators (and inverses) greedily to shrink the L1 size of the pair; returns reduced pair"""
    la = np.array(la); lb = np.array(lb)
    size = lambda a, b: int(np.abs(a).sum() + np.abs(b).sum())
    cur = size(la, lb)
    for _ in range(max_iter):
        best = None
        for M in gens_and_inv:
            na, nb = M @ la, M @ lb
            sz = size(na, nb)
            if sz < cur:
                cur = sz; best = (na, nb)
        if best is None:
            break
        la, lb = best
    return la, lb

def even_overlattices(m):
    """Number of even integral overlattices of M = diag(m,m) (Gram of lambda_a, lambda_b): subgroups H of (Z/m)^2 such that every
    element (a,b) has norm (a^2+b^2)/m in 2Z and all pairs have (a a'+b b')/m in Z.  Nikulin-type consistency check, not a derivation."""
    els = [(a, b) for a in range(m) for b in range(m)]
    def gen(gs):
        H = {(0, 0)}
        frontier = [(0, 0)]
        while frontier:
            x = frontier.pop()
            for g in gs:
                y = ((x[0] + g[0]) % m, (x[1] + g[1]) % m)
                if y not in H:
                    H.add(y); frontier.append(y)
        return frozenset(H)
    subs = set()
    for g1 in els:
        for g2 in els:
            subs.add(gen([g1, g2]))
    good = 0
    for Hs in subs:
        ok = all(((a * a + b * b) % (2 * m) == 0) for a, b in Hs) and all(((a * c + b * d) % m == 0) for a, b in Hs for c, d in Hs)
        good += int(ok)
    return good

def orbits_burnside(S, pairs_i, pairs_j, Gmats, rank, Hn, only_plus=None):
    """S: (n,rank) vectors; the pair set is {(i,j)} ordered.  Number of orbits under the group by Burnside; returns (order, orbits)."""
    total = 0
    order = 0
    for M in Gmats:
        Sg = S @ M.T
        fixed = np.all(Sg == S, axis=1)
        idx = np.nonzero(fixed)[0]
        # count ordered pairs among fixed vectors with dot 0 (norms equal automatically by S_m)
        if len(idx) == 0:
            order += 1; continue
        F = S[idx]
        total += count_pairs(F, Hn)
        order += 1
    assert total % order == 0, (total, order)
    return order, total // order

