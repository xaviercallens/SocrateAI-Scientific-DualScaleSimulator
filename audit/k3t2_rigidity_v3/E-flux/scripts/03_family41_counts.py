def hnf_key(ga, gb):
    """HNF of the column lattice of [ga; gb] (2 x r) -- computed by an explicit two-step gcd reduction (exact)."""
    cols = [(int(p), int(q)) for p, q in zip(ga, gb) if (p or q)]
    # reduce: lattice L in Z^2 generated by cols.  Compute d = gcd of q's ; then a = gcd of {p} over combos with q=0 ...
    # do Euclid on pairs
    basis_top = None
    rows = list(cols)
    # bring to echelon by repeated Euclid on second coordinate
    vecs = [list(c) for c in rows]
    pivot = None
    # collect gcd vector with second coordinate = d
    top = None
    rest = []
    for v in vecs:
        if top is None:
            if v[1] != 0:
                top = v[:]
            else:
                rest.append(v)
            continue
        # Euclid between top and v on second coordinate
        a, b = top, v[:]
        while b[1] != 0:
            q = a[1] // b[1]
            a = [a[0] - q * b[0], a[1] - q * b[1]]
            a, b = b, a
        top = a
        rest.append(b)     # b has second coord 0
    if top is not None and top[1] < 0:
        top = [-top[0], -top[1]]
    p0 = 0
    for v in rest:
        p0 = math.gcd(p0, abs(v[0]))
    if top is None:
        return (0, 0, p0)
    a = top[0] % p0 if p0 else top[0]
    return (a, top[1], p0)


