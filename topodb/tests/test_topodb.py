class TestCompare:
    """The hand-computed cases.

    Two trivial diagrams, one point each: A={(0,1)}, B={(0,1.5)}.
      * matching the points costs max(|0-0|, |1-1.5|) = 0.5
      * sending both to the diagonal costs max(1/2, 1.5/2) = 0.75
    so the bottleneck distance is min(0.5, 0.75) = 0.5, by hand.
    (The pair (0,1) vs (0,2) is deliberately NOT used: both strategies cost 1.0
    there, so it would not discriminate between them.)

    And A={} vs B={(0,1)}: the only option is the diagonal, 1/2 = 0.5.
    1-Wasserstein on A={(0,1)} vs B={(0,1.5)} is the single matched cost, 0.5.
    """

    def _two_runs(self, db, bars_a, bars_b, dim=1):
        _dataset(db)
        ra, rb = _run(db), _run(db)
        if bars_a:
            db.add_bars(ra, dim, bars_a)
        if bars_b:
            db.add_bars(rb, dim, bars_b)
        return ra, rb

    def test_bottleneck_matches_hand_computation(self, db):
        ra, rb = self._two_runs(db, [(0.0, 1.0)], [(0.0, 1.5)])
        d, info = compare.bottleneck(ra, rb, 1, db=db)
        assert d == pytest.approx(0.5, abs=1e-9)
        assert info["metric"] == "bottleneck" and info["methods_comparable"] is True
        assert "truncated to the top 50" in info["caveat"]

    def test_bottleneck_against_an_empty_diagram_is_half_the_persistence(self, db):
        ra, rb = self._two_runs(db, [], [(0.0, 1.0)])
        d, _ = compare.bottleneck(ra, rb, 1, db=db)
        assert d == pytest.approx(0.5, abs=1e-9)

    def test_bottleneck_of_a_run_with_itself_is_zero(self, db):
        ra, _ = self._two_runs(db, [(0.0, 1.0), (0.2, 0.9)], [(0.0, 1.0)])
        d, _ = compare.bottleneck(ra, ra, 1, db=db)
        assert d == pytest.approx(0.0)

    def test_wasserstein_matches_hand_computation(self, db):
        ra, rb = self._two_runs(db, [(0.0, 1.0)], [(0.0, 1.5)])
        d, info = compare.wasserstein(ra, rb, 1, db=db, order=1.0)
        assert d == pytest.approx(0.5, abs=1e-6)
        assert "wasserstein" in info["metric"]

    def test_infinite_bars_are_dropped_by_default_and_counted(self, db):
        ra, rb = self._two_runs(db, [(0.0, None), (0.0, 1.0)], [(0.0, 1.5)], dim=0)
        d, info = compare.bottleneck(ra, rb, 0, db=db)
        assert d == pytest.approx(0.5, abs=1e-9)
        assert info["run_a"]["n_infinite_dropped"] == 1
        assert info["run_a"]["n_points_used"] == 1 and info["run_a"]["n_bars_stored"] == 2

    def test_keeping_infinite_bars_gives_an_infinite_distance(self, db):
        ra, rb = self._two_runs(db, [(0.0, None)], [(0.0, 1.5)], dim=0)
        d, _ = compare.bottleneck(ra, rb, 0, db=db, infinite="keep")
        assert d == float("inf"), "this is why 'drop' is the default"

    def test_capping_infinite_bars(self, db):
        ra, rb = self._two_runs(db, [(0.0, None)], [(0.0, 1.5)], dim=0)
        d, _ = compare.bottleneck(ra, rb, 0, db=db, infinite="cap", cap_value=2.0)
        assert d == pytest.approx(0.5, abs=1e-9)

    def test_nearest_excludes_runs_without_bars_and_says_how_many(self, db):
        _dataset(db)
        ref = _run(db)
        db.add_bars(ref, 1, [(0.0, 1.0)])
        close = _run(db)
        db.add_bars(close, 1, [(0.0, 1.1)])
        far = _run(db)
        db.add_bars(far, 1, [(0.0, 9.0)])
        chain = db.add_run(dataset_id="synthetic/circle", method="chain_complex", coeff_field=0,
                           params={}, script="s", command="c", tier="B")
        db.add_betti(chain, {2: 22})                       # Betti but no filtration, hence no bars

        res = compare.nearest(ref, k=2, dim=1, db=db)
        assert [n["run_id"] for n in res["neighbours"]] == [close, far]
        assert res["neighbours"][0]["distance"] == pytest.approx(0.1, abs=1e-9)
        assert res["excluded_no_bars"] == 1
        assert res["n_compared"] == 2
        assert "truncated to the top 50" in res["caveat"]

    def test_nearest_refuses_to_mix_methods_by_default(self, db):
        _dataset(db)
        ref = _run(db, method="alpha")
        db.add_bars(ref, 1, [(0.0, 1.0)])
        other = _run(db, method="rips")
        db.add_bars(other, 1, [(0.0, 1.0)])
        assert compare.nearest(ref, dim=1, db=db)["excluded_other_method"] == 1
        assert compare.nearest(ref, dim=1, db=db)["neighbours"] == []
        mixed = compare.nearest(ref, dim=1, db=db, same_method=False)
        assert [n["run_id"] for n in mixed["neighbours"]] == [other]

    def test_missing_run_raises(self, db):
        with pytest.raises(KeyError):
            compare.load_diagram(db, 999, 1)


