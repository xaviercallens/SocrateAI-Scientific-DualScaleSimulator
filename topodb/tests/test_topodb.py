def _seed_cli_db(path):
    db = TopoDB(path)
    db.add_dataset(id="synthetic/circle", domain="synthetic", title="unit circle",
                   source="generated by test", provenance="synthetic_control", n_objects=200)
    db.add_dataset(id="mathematics/k3", domain="mathematics", title="resolved K3",
                   source="Mayer-Vietoris", provenance="synthetic_control")
    r = db.add_run(dataset_id="synthetic/circle", method="alpha", coeff_field=2, max_dim=2,
                   params={"max_alpha_sq": "inf"}, script="s.py", command="python s.py", tier="X")
    db.add_betti(r, {0: 1, 1: 1, 2: 0}, expected={0: 1, 1: 1, 2: 0})
    db.add_bars(r, 1, [(0.03, 0.86), (0.03, 0.05)])
    db.add_bars(r, 0, [(0.0, None)])
    db.add_statistic(r, "p1_over_p2", 47.86)
    db.add_control(r, "known_answer", "circle recovers b1=1", passed=True, detail="ratio 47.9")
    db.add_finding(run_id=r, claim="the circle is recovered", verdict="recovered", tier="X")
    r2 = db.add_run(dataset_id="synthetic/circle", method="alpha", coeff_field=2,
                    params={}, script="s.py", command="python s.py", tier="X")
    db.add_bars(r2, 1, [(0.03, 0.9)])
    chain = db.add_run(dataset_id="mathematics/k3", method="chain_complex", coeff_field=0,
                       params={"N": 8}, script="mv.py", command="python mv.py", tier="B")
    db.add_betti(chain, {0: 1, 1: 0, 2: 22, 3: 0, 4: 1})
    db.add_finding(run_id=chain, claim="b2=22 for the resolved K3", verdict="recovered", tier="B")
    return db, r, r2, chain


