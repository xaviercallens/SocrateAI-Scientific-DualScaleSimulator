class TestReport:
    def test_report_separates_prestated_from_ungated(self, db, tmp_path):
        _dataset(db)
        db.add_dataset(id="astro/wmap", domain="astro", title="WMAP ILC9", source="LAMBDA",
                       provenance="observation")
        gated = _run(db)
        db.add_betti(gated, {1: 1}, expected={1: 1})
        db.add_control(gated, "known_answer", "circle b1=1", passed=True)
        ungated = db.add_run(dataset_id="astro/wmap", method="cubical", coeff_field=2, params={},
                             script="s", command="c", tier="X")
        db.add_betti(ungated, {1: 4})
        db.add_finding(run_id=ungated, claim="no excess", verdict="null", tier="X")
        db.add_statistic(ungated, "iqr_over_median", 0.45)

        data = report.build(db)
        assert data["runs_by_tier"] == {"X": 2}
        assert data["betti_vs_prestated_expectation"]["matched"] == 1
        assert data["betti_vs_prestated_expectation"]["no_expectation_recorded"] == 1
        ka = data["known_answer_controls"]
        assert [d["dataset"] for d in ka["all_passed"]] == ["synthetic/circle"]
        assert "astro/wmap" in [d["dataset"] for d in ka["datasets_with_no_known_answer_control"]]
        assert [f["verdict"] for f in data["findings_null_or_inconclusive"]] == ["null"]
        assert data["totals"]["statistics_without_p_value"] == 1
        assert data["runs_without_any_bars"]["count"] == 2

        out = tmp_path / "r.json"
        report.write(str(out), db)
        assert json.loads(out.read_text())["totals"]["runs"] == 2

    def test_report_lists_failed_known_answer_controls(self, db):
        _dataset(db)
        r = _run(db)
        db.add_control(r, "known_answer", "RP2 over Z/3", passed=False, detail="over budget")
        data = report.build(db)
        assert data["known_answer_controls"]["all_passed"] == []
        assert data["known_answer_controls"]["some_failed"][0]["n_failed"] == 1


