class TestRoundTrip:
    def test_full_run_round_trips(self, db):
        _dataset(db)
        run = db.add_run(dataset_id="synthetic/circle", method="alpha", coeff_field=2, max_dim=2,
                         params={"max_alpha_sq": "inf", "n": 200}, preprocessing="none",
                         script="simple_suite.py", command="python simple_suite.py --case P1",
                         tier="X", seed="0", wall_sec=0.79, peak_mb=173.8)
        db.add_betti(run, {0: 1, 1: 1, 2: 0}, expected={0: 1, 1: 1, 2: 0})
        db.add_bars(run, 1, [(0.03, 0.86), (0.032, 0.049), (0.027, 0.043)])
        db.add_bars(run, 0, [(0.0, None), (0.0, 0.048)])
        db.add_statistic(run, "p1_over_p2", 47.86)
        db.add_statistic(run, "h1_bar1", 1.0, null_model="50 uniform-box nulls", n_null=50,
                         p_value=0.0196, p_method="rank")
        db.add_control(run, "known_answer", "circle recovers b1=1", passed=True, detail="ratio 47.9")
        fid = db.add_finding(run_id=run, claim="alpha recovers the circle", verdict="recovered",
                             tier="X", caveat="one seed", reference="report.json")

        r = db.con.execute("SELECT * FROM run WHERE id=?", (run,)).fetchone()
        assert r["method"] == "alpha" and r["tier"] == "X" and r["seed"] == "0"
        assert json.loads(r["params_json"]) == {"max_alpha_sq": "inf", "n": 200}
        assert r["created"] and r["command"].endswith("--case P1")

        betti = {row["dim"]: (row["value"], row["expected"], row["matches"])
                 for row in db.con.execute("SELECT * FROM betti WHERE run_id=?", (run,))}
        assert betti == {0: (1, 1, 1), 1: (1, 1, 1), 2: (0, 0, 1)}

        bars1 = db.con.execute(
            "SELECT birth, death, rank FROM bar WHERE run_id=? AND dim=1 ORDER BY rank",
            (run,)).fetchall()
        assert [b["rank"] for b in bars1] == [1, 2, 3]
        assert bars1[0]["birth"] == pytest.approx(0.03) and bars1[0]["death"] == pytest.approx(0.86)

        bars0 = db.con.execute(
            "SELECT birth, death, rank FROM bar WHERE run_id=? AND dim=0 ORDER BY rank",
            (run,)).fetchall()
        assert bars0[0]["death"] is None, "the infinite bar must rank first and store death NULL"

        assert db.con.execute("SELECT count(*) FROM statistic WHERE run_id=?",
                              (run,)).fetchone()[0] == 2
        c = db.con.execute("SELECT * FROM control WHERE run_id=?", (run,)).fetchone()
        assert c["passed"] == 1 and c["kind"] == "known_answer"
        f = db.con.execute("SELECT * FROM finding WHERE id=?", (fid,)).fetchone()
        assert f["verdict"] == "recovered" and f["run_id"] == run

    def test_bars_are_ranked_by_persistence_and_truncated(self, db):
        _dataset(db)
        run = _run(db)
        bars = [(0.0, 0.1 * i) for i in range(1, 80)]
        db.add_bars(run, 1, bars)
        rows = db.con.execute(
            "SELECT birth, death, rank FROM bar WHERE run_id=? ORDER BY rank", (run,)).fetchall()
        assert len(rows) == 50, "add_bars keeps the top 50 by default -- the truncation compare.py warns about"
        assert rows[0]["death"] == pytest.approx(7.9)
        deaths = [r["death"] for r in rows]
        assert deaths == sorted(deaths, reverse=True)

    def test_search_finds_datasets_and_findings(self, db):
        _dataset(db, id="astro/wmap_ilc9", domain="astro")
        db.add_finding(dataset_id="astro/wmap_ilc9", claim="no vortex excess over the null",
                       verdict="null", tier="X")
        assert any(r["kind"] == "finding" for r in db.search("vortex"))

    def test_summary_counts(self, db):
        _dataset(db)
        r = _run(db, tier="B")
        db.add_bars(r, 1, [(0.0, 1.0)])
        db.add_control(r, "known_answer", "k", passed=True)
        db.add_finding(run_id=r, claim="c", verdict="null", tier="B")
        s = db.summary()
        assert s["datasets_by_domain"] == {"synthetic": 1}
        assert s["runs_by_tier"] == {"B": 1} and s["runs_by_method"] == {"alpha": 1}
        assert s["controls_passed"] == {"passed": 1}
        assert s["findings_by_verdict"] == {"null": 1} and s["bars"] == 1


