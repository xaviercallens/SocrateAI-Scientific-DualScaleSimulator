def _dataset(db, id="synthetic/circle", domain="synthetic"):
    return db.add_dataset(id=id, domain=domain, title="unit circle, 200 points",
                          source="generated by test", provenance="synthetic_control",
                          n_objects=200, ambient_dim=2)


def _run(db, dataset_id="synthetic/circle", tier="X", method="alpha"):
    return db.add_run(dataset_id=dataset_id, method=method, coeff_field=2, max_dim=2,
                      params={"max_alpha_sq": "inf"}, script="test_topodb.py",
                      command="pytest", tier=tier, seed="0")


# --------------------------------------------------------------- refusals
class TestRefusalRules:
    def test_p_value_without_null_model_is_refused(self, db):
        _dataset(db)
        r = _run(db)
        with pytest.raises(ValueError, match="p_value requires null_model and n_null"):
            db.add_statistic(r, "iqr_over_median", 0.45, p_value=0.01, n_null=100)
        with pytest.raises(ValueError, match="p_value requires null_model and n_null"):
            db.add_statistic(r, "iqr_over_median", 0.45, p_value=0.01, null_model="uniform box")
        assert db.con.execute("SELECT count(*) FROM statistic").fetchone()[0] == 0

    def test_statistic_without_p_value_is_accepted(self, db):
        """A source with no null must be storable: the statistic alone, no invented p."""
        _dataset(db)
        r = _run(db)
        db.add_statistic(r, "psi6", 0.83)
        row = db.con.execute("SELECT * FROM statistic").fetchone()
        assert row["p_value"] is None and row["null_model"] is None and row["value"] == 0.83

    def test_p_value_with_its_null_is_accepted(self, db):
        _dataset(db)
        r = _run(db)
        db.add_statistic(r, "h1_bar1", 1.0, null_model="50 matched uniform-box nulls",
                         n_null=50, p_value=1 / 51, p_method="rank")
        row = db.con.execute("SELECT * FROM statistic").fetchone()
        assert row["n_null"] == 50 and row["p_value"] == pytest.approx(1 / 51)

    def test_matches_requires_expected(self, db):
        """`matches` is NULL unless the source pre-stated an expectation."""
        _dataset(db)
        r1, r2 = _run(db), _run(db)
        db.add_betti(r1, {0: 1, 1: 1, 2: 0})                       # no pre-registration
        db.add_betti(r2, {0: 1, 1: 1, 2: 0}, expected={0: 1, 1: 1, 2: 0})
        no_exp = db.con.execute("SELECT * FROM betti WHERE run_id=?", (r1,)).fetchall()
        assert all(row["expected"] is None and row["matches"] is None for row in no_exp)
        with_exp = db.con.execute("SELECT * FROM betti WHERE run_id=?", (r2,)).fetchall()
        assert all(row["matches"] == 1 for row in with_exp)

    def test_matches_is_zero_on_disagreement(self, db):
        _dataset(db)
        r = _run(db)
        db.add_betti(r, {2: 21}, expected={2: 22})
        row = db.con.execute("SELECT * FROM betti WHERE run_id=?", (r,)).fetchone()
        assert row["matches"] == 0 and row["value"] == 21 and row["expected"] == 22

    def test_partial_expectation_leaves_the_rest_ungated(self, db):
        _dataset(db)
        r = _run(db)
        db.add_betti(r, {0: 1, 1: 2, 2: 1}, expected={1: 2})
        rows = {row["dim"]: row for row in db.con.execute(
            "SELECT * FROM betti WHERE run_id=?", (r,)).fetchall()}
        assert rows[1]["matches"] == 1
        assert rows[0]["matches"] is None and rows[2]["matches"] is None

    @pytest.mark.parametrize("tier", ["Z", "a", "proved", ""])
    def test_bad_tier_is_refused(self, db, tier):
        _dataset(db)
        with pytest.raises(ValueError, match="tier must be one of"):
            _run(db, tier=tier)
        with pytest.raises(ValueError, match="tier must be one of"):
            db.add_finding(claim="x", verdict="null", tier=tier)

    def test_bad_method_is_refused(self, db):
        _dataset(db)
        with pytest.raises(ValueError, match="method must be one of"):
            _run(db, method="lower_star")   # the schema's name is lower_star_graph

    def test_bad_verdict_is_refused_by_the_schema(self, db):
        import sqlite3
        _dataset(db)
        r = _run(db)
        with pytest.raises(sqlite3.IntegrityError):
            db.add_finding(claim="x", verdict="proved", tier="X", run_id=r)

    def test_unknown_domain_is_refused_by_the_schema(self, db):
        import sqlite3
        with pytest.raises(sqlite3.IntegrityError):
            db.add_dataset(id="x/y", domain="cosmology", title="t", source="s",
                           provenance="observation")


