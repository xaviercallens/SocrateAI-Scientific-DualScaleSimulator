def validate_output(csv_file):
    # 4. Epistemic Bounding - Output Validator
    print(f"Validating simulation output: {csv_file}")
    df = pd.read_csv(csv_file)
    
    final_x = df['x'].iloc[-1]
    final_y = df['y'].iloc[-1]
    
    # Exact target
    target_x = 0.5
    target_y = float((sympy.sqrt(3)/2).evalf())
    
    # Hyperbolic distance: cosh(d) = 1 + ((x2-x1)^2 + (y2-y1)^2) / (2 * y1 * y2)
    num = (final_x - target_x)**2 + (final_y - target_y)**2
    den = 2.0 * final_y * target_y
    cosh_d = 1.0 + num / den
    # Prevent math domain error for floating point inaccuracies
    cosh_d = max(1.0, cosh_d)
    
    dist = np.arccosh(cosh_d)
    
    tolerance = 1e-3
    print(f"Final state: tau = {final_x:.5f} + {final_y:.5f}i")
    print(f"Hyperbolic distance to exact Orbifold attractor: {dist:.5e}")
    
    if dist <= tolerance:
        print(f"VALIDATION PASS: Drift is bounded within formal tolerance epsilon={tolerance}")
        sys.exit(0)
    else:
        print(f"VALIDATION FAIL: Drift {dist:.5e} exceeds formal tolerance epsilon={tolerance}")
        sys.exit(1)

